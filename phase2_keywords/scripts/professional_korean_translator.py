        # Find document type or educational prefix if present
        doc_type = None
        edu_prefix = None
        other_parts = []
        
        for part in unique_parts:
            if part in doc_types:
                doc_type = part
            elif part in educational_prefixes:
                edu_prefix = part
            else:
                other_parts.append(part)
        
        # Construct natural Korean phrase
        if edu_prefix:
            formatted_parts.append(edu_prefix)
        if doc_type:
            formatted_parts.append(doc_type)
        if other_parts:
            formatted_parts.extend(other_parts)
        
        if not formatted_parts:
            formatted_parts = unique_parts
        
        # Join with spaces (Korean uses spaces between words)
        result = ' '.join(formatted_parts)
        
        return result

