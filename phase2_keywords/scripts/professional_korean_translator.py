    def validate_translations(self, english_file: str, korean_file: str) -> Dict[str, any]:
        """Validate Korean translation quality and provide statistics."""
        try:
            with open(english_file, 'r', encoding='utf-8') as f:
                english_keywords = [line.strip() for line in f if line.strip()]
            
            with open(korean_file, 'r', encoding='utf-8') as f:
                korean_keywords = [line.strip() for line in f if line.strip()]
            
            # Basic validation
            validation_results = {
                'english_count': len(english_keywords),
                'korean_count': len(korean_keywords),
                'exact_match': len(english_keywords) == len(korean_keywords),
                'coverage_rate': (len(korean_keywords) / len(english_keywords)) * 100 if english_keywords else 0,
                'empty_translations': sum(1 for k in korean_keywords if not k.strip()),
                'average_length': sum(len(k) for k in korean_keywords) / len(korean_keywords) if korean_keywords else 0,
            }
            
            # Quality checks for Korean
            validation_results['quality_checks'] = {
                'contains_korean_only': sum(1 for k in korean_keywords if self._is_korean_only(k)),
                'educational_terms': sum(1 for k in korean_keywords if any(term in k for term in ['교육', '학술', '학습', '교학', '훈련'])),
                'proper_formatting': sum(1 for k in korean_keywords if self._is_well_formatted_korean(k))
            }
            
            return validation_results
            
        except Exception as e:
            logger.error(f"검증 실패: {e}")
            return {'error': str(e)}

    def _is_korean_only(self, text: str) -> bool:
        """Check if text contains only Korean characters and spaces."""
        # Korean Unicode ranges: Hangul (AC00-D7AF), Hangul Jamo (1100-11FF), Hangul Compatibility Jamo (3130-318F)
        korean_pattern = r'^[\uAC00-\uD7AF\u1100-\u11FF\u3130-\u318F\s]+$'
        return bool(re.match(korean_pattern, text.strip()))

    def _is_well_formatted_korean(self, text: str) -> bool:
        """Check if Korean text is well formatted."""
        text = text.strip()
        if not text:
            return False
        
        # Should have reasonable length (not too short or too long)
        if len(text) < 1 or len(text) > 100:
            return False
        
        # Should contain mostly Korean characters
        korean_chars = len(re.findall(r'[\uAC00-\uD7AF\u1100-\u11FF\u3130-\u318F]', text))
        if korean_chars < len(text.replace(' ', '')) * 0.7:  # At least 70% Korean characters
            return False
        
        return True


