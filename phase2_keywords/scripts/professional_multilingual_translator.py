    def normalize_english_keyword(self, keyword: str) -> str:
        """Normalize and analyze English keyword"""
        # Clean the keyword
        cleaned = re.sub(r'[^\w\s\-]', ' ', keyword.lower())
        cleaned = re.sub(r'\s+', ' ', cleaned).strip()
        
        # Handle morphological variations
        words = cleaned.split()
        normalized_words = []
        
        for word in words:
            # Check for plurals
            if word in self.morphological_rules['plurals']:
                normalized_words.append(self.morphological_rules['plurals'][word])
            # Check for gerunds
            elif word in self.morphological_rules['gerunds']:
                normalized_words.append(self.morphological_rules['gerunds'][word])
            # Check for past participles
            elif word in self.morphological_rules['past_participles']:
                normalized_words.append(self.morphological_rules['past_participles'][word])
            # Check for adjectives
            elif word in self.morphological_rules['adjectives']:
                normalized_words.append(self.morphological_rules['adjectives'][word])
            else:
                normalized_words.append(word)
        
        return ' '.join(normalized_words)
    
    def get_unique_translation(self, english_keyword: str) -> str:
        """Generate a unique, high-quality translation"""
        
        # First check for exact phrase matches
        normalized = self.normalize_english_keyword(english_keyword)
        
        if normalized in self.phrase_dictionary:
            options = self.phrase_dictionary[normalized]
            # Use counter to cycle through options for uniqueness
            index = self.translation_counter[normalized] % len(options)
            self.translation_counter[normalized] += 1
            return options[index]
        
        # Parse compound keywords
        return self._translate_compound_keyword(normalized)
    
    def _translate_compound_keyword(self, keyword: str) -> str:
        """Translate compound keywords with semantic understanding"""
        words = keyword.split()
        
        if len(words) == 1:
            return self._translate_single_word(words[0])
        elif len(words) == 2:
            return self._translate_two_word_phrase(words[0], words[1])
        elif len(words) >= 3:
            return self._translate_multi_word_phrase(words)
        
        return self._translate_single_word(keyword)
    
    def _translate_single_word(self, word: str) -> str:
        """Translate single word with variation"""
        if word in self.word_dictionary:
            options = self.word_dictionary[word]
            index = self.translation_counter[word] % len(options)
            self.translation_counter[word] += 1
            return options[index]
        
        # Handle unknown words with educational context
        if self.target_language == 'arabic':
            return f"مصطلح {word}"
        elif self.target_language == 'chinese':
            return f"{word}术语"
        elif self.target_language == 'korean':
            return f"{word} 용어"
        
        return word
    
    def _translate_two_word_phrase(self, word1: str, word2: str) -> str:
        """Translate two-word phrases naturally"""
        
        # Get individual translations
        trans1 = self._get_word_translation(word1)
        trans2 = self._get_word_translation(word2)
        
        # Apply language-specific combination rules
        if self.target_language == 'arabic':
            return self._combine_arabic_words(trans1, trans2, word1, word2)
        elif self.target_language == 'chinese':
            return self._combine_chinese_words(trans1, trans2, word1, word2)
        elif self.target_language == 'korean':
            return self._combine_korean_words(trans1, trans2, word1, word2)
        
        return f"{trans1} {trans2}"
    
